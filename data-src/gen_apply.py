#!/usr/bin/env python3
"""gen/gens.txt (line-ups written with player names) -> squads_gen.txt + players_gen.txt.
Names are matched to app players (English name or alias, same era); unknown players come from gen/names.txt:
   English name|nation|Arabic name|position"""
import json, os, re, sys, unicodedata, collections
H = os.path.dirname(os.path.abspath(__file__))
def norm(s): return ' '.join(re.sub(r'[^a-z0-9 ]', ' ', unicodedata.normalize('NFD', (s or '').lower()).encode('ascii', 'ignore').decode()).split())
src = open(os.path.join(H, '..', 'www', 'js', 'data.js'), encoding='utf-8').read()
D = json.loads(src[src.index('{'):src.rindex('}') + 1])
P = {k: v for k, v in D['players'].items() if not k.startswith('g-')}
idx = collections.defaultdict(set)
for p in P.values():
    for n in [p['en']] + p.get('al', []):
        if norm(n): idx[norm(n)].add(p['id'])
NEW = {}
for l in open(os.path.join(H, 'gen', 'names.txt'), encoding='utf-8'):
    if l.strip() and not l.startswith('#'):
        en, nat, ar, pos = l.rstrip('\n').split('|'); NEW[norm(en)] = (en, nat, ar, pos)
def gid(en): return 'g-' + norm(en).replace(' ', '-')
def by(pid): return int((P[pid].get('b') or '0')[:4] or 0)
out, players, missing, amb = [], {}, [], []
cur = None
for ln, l in enumerate(open(os.path.join(H, 'gen', 'gens.txt'), encoding='utf-8'), 1):
    l = l.rstrip('\n')
    if not l.strip() or l.startswith('#'): continue
    if l.startswith('@') or l.startswith('>'):
        if l.startswith('@'): cur = l.split('|'); season = int(cur[2]); out.append('')
        out.append(l); continue
    no, pos, ref = l.split('|')
    nat = None
    if ref.startswith('='): pid = ref[1:]
    else:
        if '@' in ref: ref, nat = ref.split('@')
        c = [x for x in idx.get(norm(ref), ()) if (not nat or P[x]['nat'] == nat)]
        c = [x for x in c if not by(x) or 15 <= season - by(x) <= 41]
        if len(c) > 1:   # curated record first, then World Cup, then StatsBomb records
            rank = lambda x: 3 if x.startswith('sb') else 1 if re.match(r'w\d', x) else 0
            best = min(map(rank, c)); cur_ = [x for x in c if rank(x) == best]
            if len(cur_) > 1: amb.append((ln, ref, c))
            c = cur_[:1]
        if c: pid = c[0]
        elif norm(ref) in NEW:
            en, nat2, ar, pos2 = NEW[norm(ref)]; pid = gid(en)
            players[pid] = f'{pid}|{en}|{ar}|{nat2}|{pos2}|-|3|||-|'
        else:
            missing.append((ln, ref, pos, cur[1], season)); pid = '?'
    out.append(f'{no}|{pos}|{pid}|XI')
open(os.path.join(H, 'squads_gen.txt'), 'w', encoding='utf-8').write(
    '# Generated by gen_apply.py from gen/gens.txt — edit gen/gens.txt instead.\n' + '\n'.join(out) + '\n')
open(os.path.join(H, 'players_gen.txt'), 'w', encoding='utf-8').write(
    '# Players added with the club generations (gen/names.txt). Generated by gen_apply.py\n' + '\n'.join(sorted(players.values())) + '\n')
for a in amb: print('ambiguous', a, file=sys.stderr)
for m in missing: print('missing', '|'.join(map(str, m)))
print(len([l for l in out if l.startswith('@')]), 'line-ups;', len(players), 'new players;', len(missing), 'missing', file=sys.stderr)
